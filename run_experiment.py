def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--quick", action="store_true", help="Reduced seeds/episodes for smoke test")
    parser.add_argument(
        "--target-backend",
        choices=("local-density-matrix", "originq-superconducting", "tiangong-kaiwu-cim"),
        default="local-density-matrix",
        help="Migration target recorded in metadata; execution remains local simulation",
    )
    args = parser.parse_args()
    cfg = Config()
    if args.quick:
        cfg = Config(delays=(4, 32, 64), seeds=3, train_episodes=180,
                     eval_episodes=500, shots=256, memory_noise=.001,
                     learning_rate=.075, esn_radius=.78, feature_noise=.025)

    root = args.output_root.resolve()
    code_dir = root / "code"
    fig_dir = root / "figure"
    code_dir.mkdir(parents=True, exist_ok=True)
    fig_dir.mkdir(parents=True, exist_ok=True)
    set_style()
    start = time.time()
    qrc = QuantumReservoir(memory_noise=cfg.memory_noise)
    esn = EchoStateReservoir(radius=cfg.esn_radius)

    results, curves = run_main_benchmark(cfg, qrc, esn)
    summary = summarize(results)
    probe = memory_probe(qrc, esn)
    noise = run_noise_sweep(cfg, qrc, esn) if not args.quick else run_noise_sweep(cfg, qrc, esn)

    results.to_csv(fig_dir / "raw_results.csv", index=False, encoding="utf-8-sig")
    summary.to_csv(fig_dir / "summary_results.csv", index=False, encoding="utf-8-sig")
    curves.to_csv(fig_dir / "learning_curves.csv", index=False, encoding="utf-8-sig")
    probe.to_csv(fig_dir / "memory_probe.csv", index=False, encoding="utf-8-sig")
    noise.to_csv(fig_dir / "noise_sweep.csv", index=False, encoding="utf-8-sig")

    plot_success(summary, fig_dir)
    plot_learning(curves, fig_dir)
    plot_memory(probe, qrc, fig_dir)
    plot_noise(noise, fig_dir)
    plot_ablation(summary, fig_dir)
    resources = plot_resource(summary, fig_dir)
    resources.to_csv(fig_dir / "resource_comparison.csv", index=False, encoding="utf-8-sig")
    plot_dashboard(summary, curves, noise, probe, fig_dir)

    (code_dir / "requirements.txt").write_text(
        "numpy>=2.0\nscipy>=1.14\npandas>=2.2\nmatplotlib>=3.9\nseaborn>=0.13\n",
        encoding="utf-8")
    if Path(__file__).resolve() != (code_dir / "run_experiment.py").resolve():
        (code_dir / "run_experiment.py").write_text(Path(__file__).read_text(encoding="utf-8"), encoding="utf-8")
